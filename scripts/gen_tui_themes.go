//go:build ignore

// gen_tui_themes writes the built-in TUI themes from a local clone of
// https://github.com/mbadolato/iTerm2-Color-Schemes. Run it from the repository root:
//
//	go run scripts/gen_tui_themes.go <path of the clone>
//
// It reads the ghostty/<name> files, licenses.yml, CREDITS.md and LICENSE of the clone and writes
// internal/tui/themes_builtin_gen.go (colours and names only) and internal/tui/themes_builtin_licenses.txt
// (the licence and credit notices that belong to them). The clone is untrusted data: nothing in it is run.
package main

import (
	"bufio"
	"bytes"
	_ "embed"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// scheme is a candidate: its name in the collection, and a text of CREDITS.md that names its creators.
type scheme struct{ name, credit string }

// candidates are the schemes offered, in the order of the Settings list. A scheme whose licence is not recorded
// in licenses.yml or not on allowedLicenses stops the run instead of being left out silently. Dracula, the
// Solarized pair and the Tokyo Night themes are not here: their licence is unknown, GPL or Apache-2.0, whose
// text the clone does not carry. Gruvbox is not either: its repository has no licence file with a copyright notice.
var candidates = []scheme{
	{"Catppuccin Mocha", "The Catppuccin themes"},
	{"Catppuccin Latte", "The Catppuccin themes"},
	{"Nord", "Nord theme was created"},
	{"Atom One Dark", "The AtomOneDark theme"},
	{"Atom One Light", "The AtomOneLight theme"},
	{"Rose Pine", "The Rosé Pine themes"},
	{"Rose Pine Dawn", "The Rosé Pine themes"},
	{"Selenized Dark", "The themes Selenized Dark and Light"},
	{"Selenized Light", "The themes Selenized Dark and Light"},
	{"Tomorrow Night", "The Tomorrow themes"},
}

// allowedLicenses are the SPDX licences whose notice is all that redistribution in source and binary asks.
var allowedLicenses = map[string]bool{"MIT": true, "BSD-2-Clause": true, "BSD-3-Clause": true, "ISC": true, "0BSD": true, "CC0-1.0": true, "Unlicense": true}

// notices are the copyright notices of the upstream licence files, one line per candidate (see the file). They sit
// beside the generator because the architecture test reads string literals of the scripts.
//
//go:embed gen_tui_themes_notices.txt
var noticeTable string

type upstream struct{ repo, file, commit, notice string }

func readNotices() map[string]upstream {
	out := map[string]upstream{}
	for _, l := range strings.Split(noticeTable, "\n") {
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		f := strings.Split(l, " | ")
		if len(f) != 5 {
			fail("bad line in gen_tui_themes_notices.txt: " + l)
		}
		out[f[0]] = upstream{f[1], f[2], f[3], f[4]}
	}
	return out
}

type colours struct {
	fg, bg string
	ansi   [16]string
}

func main() {
	if len(os.Args) != 2 {
		fail("usage: go run scripts/gen_tui_themes.go <path of the iTerm2-Color-Schemes clone>")
	}
	src := os.Args[1]
	commit := commitOf(src)
	licenses := readLicenses(filepath.Join(src, "licenses.yml"))
	credits := readLines(filepath.Join(src, "CREDITS.md"))
	notices := readNotices()
	collectionLicense, err := os.ReadFile(filepath.Join(src, "LICENSE"))
	check(err)

	var code, notice bytes.Buffer
	fmt.Fprintf(&code, "// Code generated by scripts/gen_tui_themes.go from mbadolato/iTerm2-Color-Schemes at commit %s; DO NOT EDIT.\n\n", commit)
	code.WriteString("package tui\n\n// builtinSchemes are the colours of the schemes the theme setting offers besides the qatlas ones; their notices are in\n// themes_builtin_licenses.txt.\nvar builtinSchemes = []builtinScheme{\n")
	fmt.Fprintf(&notice, "Colour values and names of the built-in TUI themes come from the iTerm2-Color-Schemes collection\n(https://github.com/mbadolato/iTerm2-Color-Schemes, commit %s).\nThe collection is licensed as follows:\n\n%s\n", commit, strings.TrimSpace(string(collectionLicense)))
	notice.WriteString("\nThe schemes are licensed by their creators as recorded in the collection (licenses.yml, CREDITS.md),\neach under the MIT terms above with the copyright notice of its upstream licence file:\n")
	for _, s := range candidates {
		l, ok := licenses[s.name]
		if !ok || !allowedLicenses[l.license] {
			fail(fmt.Sprintf("%s: licence %q is not recorded or not allowed", s.name, l.license))
		}
		u, ok := notices[s.name]
		if !ok {
			fail(s.name + ": no copyright notice in gen_tui_themes_notices.txt")
		}
		line, text := creditOf(credits, s.credit)
		if line == 0 {
			fail(fmt.Sprintf("%s: no credit in CREDITS.md for %q", s.name, s.credit))
		}
		c := readColours(filepath.Join(src, "ghostty", s.name))
		fmt.Fprintf(&code, "\t{name: %q, fg: rgb%s, bg: rgb%s, ansi: [16]rgb{\n", strings.ToLower(s.name), rgbLit(c.fg), rgbLit(c.bg))
		for i := 0; i < 16; i += 4 {
			fmt.Fprintf(&code, "\t\t%s, %s, %s, %s,\n", rgbLit(c.ansi[i]), rgbLit(c.ansi[i+1]), rgbLit(c.ansi[i+2]), rgbLit(c.ansi[i+3]))
		}
		code.WriteString("\t}},\n")
		fmt.Fprintf(&notice, "\n%s\n  License: %s\n  Source: %s\n  Credit: %s\n  Copyright: %s\n  Copyright read from: %s, file %s, commit %s\n", s.name, l.license, l.source, text, u.notice, u.repo, u.file, u.commit)
	}
	code.WriteString("}\n")
	formatted, err := format.Source(code.Bytes())
	check(err)
	check(os.WriteFile("internal/tui/themes_builtin_gen.go", formatted, 0o644))
	check(os.WriteFile("internal/tui/themes_builtin_licenses.txt", notice.Bytes(), 0o644))
}

func fail(msg string) {
	fmt.Fprintln(os.Stderr, "gen_tui_themes:", msg)
	os.Exit(1)
}

func check(err error) {
	if err != nil {
		fail(err.Error())
	}
}

// commitOf is the commit the clone is at, read from its .git directory without running git.
func commitOf(src string) string {
	head := strings.TrimSpace(string(mustRead(filepath.Join(src, ".git", "HEAD"))))
	if ref, ok := strings.CutPrefix(head, "ref: "); ok {
		if b, err := os.ReadFile(filepath.Join(src, ".git", ref)); err == nil {
			head = strings.TrimSpace(string(b))
		} else {
			for _, l := range readLines(filepath.Join(src, ".git", "packed-refs")) {
				if f := strings.Fields(l); len(f) == 2 && f[1] == ref {
					head = f[0]
				}
			}
		}
	}
	if !regexp.MustCompile(`^[0-9a-f]{40}$`).MatchString(head) {
		fail("cannot read the commit of the clone")
	}
	return head
}

func mustRead(path string) []byte {
	b, err := os.ReadFile(path)
	check(err)
	return b
}

func readLines(path string) []string {
	f, err := os.Open(path)
	check(err)
	defer f.Close()
	var lines []string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		lines = append(lines, sc.Text())
	}
	check(sc.Err())
	return lines
}

type licenseEntry struct{ license, source string }

// readLicenses reads the flat structure of licenses.yml: a name per entry, then indented key: value lines.
func readLicenses(path string) map[string]licenseEntry {
	out := map[string]licenseEntry{}
	var name string
	for _, l := range readLines(path) {
		switch {
		case strings.HasPrefix(l, "#") || strings.TrimSpace(l) == "":
		case !strings.HasPrefix(l, " ") && strings.HasSuffix(l, ":"):
			name = strings.Trim(strings.TrimSuffix(l, ":"), "'\"")
			out[name] = licenseEntry{}
		case strings.HasPrefix(l, "  license: ") && name != "":
			e := out[name]
			e.license = strings.Trim(strings.TrimPrefix(l, "  license: "), "'\"")
			out[name] = e
		case strings.HasPrefix(l, "  source: ") && name != "":
			e := out[name]
			e.source = strings.Trim(strings.TrimPrefix(l, "  source: "), "'\"")
			out[name] = e
		}
	}
	return out
}

// creditOf is the first line of CREDITS.md holding key, with its line number.
func creditOf(lines []string, key string) (int, string) {
	for i, l := range lines {
		if strings.Contains(l, key) {
			return i + 1, l
		}
	}
	return 0, ""
}

var hexRe = regexp.MustCompile(`^#[0-9a-fA-F]{6}$`)

// readColours reads a Ghostty theme file: palette = N=#rrggbb, background and foreground.
func readColours(path string) colours {
	var c colours
	seen := 0
	for _, l := range readLines(path) {
		key, val, ok := strings.Cut(l, " = ")
		if !ok {
			continue
		}
		switch key {
		case "background":
			c.bg = checkHex(path, val)
			seen++
		case "foreground":
			c.fg = checkHex(path, val)
			seen++
		case "palette":
			n, hex, ok := strings.Cut(val, "=")
			i, err := strconv.Atoi(n)
			if !ok || err != nil || i < 0 || i > 15 {
				fail(path + ": bad palette line " + l)
			}
			c.ansi[i] = checkHex(path, hex)
			seen++
		}
	}
	if seen != 18 {
		fail(fmt.Sprintf("%s: %d of 18 colours", path, seen))
	}
	for _, v := range c.ansi {
		if v == "" {
			fail(path + ": palette incomplete")
		}
	}
	return c
}

func checkHex(path, v string) string {
	if !hexRe.MatchString(v) {
		fail(path + ": bad colour " + v)
	}
	return strings.ToLower(v)
}

func rgbLit(hex string) string {
	return fmt.Sprintf("{0x%s, 0x%s, 0x%s}", hex[1:3], hex[3:5], hex[5:7])
}
