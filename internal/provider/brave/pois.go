const (
	poisPath         = "/res/v1/local/pois"
	descriptionsPath = "/res/v1/local/descriptions"
	// maxPlaceIDs is the number of ids one request takes.
	maxPlaceIDs = 20
)

// placeIDPattern is the form of a place id: letters, digits, hyphen, underscore, and trailing padding. The
// ids are short-lived and come from Brave's own answers, so a narrower form than Brave's is enough.
var placeIDPattern = regexp.MustCompile(`^[A-Za-z0-9_-]{1,128}={0,8}$`)

// placeIDsSchema is the ids argument of both endpoints.
const placeIDsSchema = `{"type":"array","minItems":1,"maxItems":20,"uniqueItems":true,"items":{"type":"string",` +
	`"minLength":1,"maxLength":136,"pattern":"^[A-Za-z0-9_-]{1,128}={0,8}$"}}`

// checkPlaceIDs refuses an empty list, more ids than a request takes, a repeated id, and an id of another
// form. The message names the rule and never the value.
func checkPlaceIDs(ids []string) error {
	if len(ids) == 0 || len(ids) > maxPlaceIDs {
		return badRequest("ids takes from 1 through 20 place ids")
	}
	for i, id := range ids {
		if !placeIDPattern.MatchString(id) {
			return badRequest("ids has a value that is not a place id of a Brave search")
		}
		if slices.Contains(ids[:i], id) {
			return badRequest("ids names a place twice")
		}
	}
	return nil
}

// idValues returns the query that sends every id as a repeated ids parameter.
func idValues(ids []string) url.Values {
	values := url.Values{}
	for _, id := range ids {
		values.Add("ids", id)
	}
	return values
}

var (
	// poisAnswerShape is the answer of the points-of-interest endpoint.
	poisAnswerShape = object(p("type", short), p("results", list(placeShape)))
	// descriptionsAnswerShape is the answer of the description endpoint; the text is generated by Brave.
	descriptionsAnswerShape = object(p("type", short),
		p("results", list(object(p("type", short), p("id", short), p("description", body)))))
)

const idsArgument = "Place ids from brave.places.search or from locations.results[].id of brave.web.search, " +
	"from 1 through 20 different ones. An id expires after about 8 hours"

func answerSchema(answer *shape) json.RawMessage {
	return json.RawMessage(`{"type":"object","properties":{` + answer.propertiesSchema() + `,"quota":` +
		quotaSchema + `},"additionalProperties":false}`)
}

