// poiDescriptionsArguments are the arguments of brave.poi-descriptions.get.
type poiDescriptionsArguments struct {
	IDs     []string `json:"ids"`
	NoCache *bool    `json:"no_cache"`
}

// preparePOIDescriptions checks every argument; the request is built only from what passed.
func preparePOIDescriptions(args poiDescriptionsArguments) (run, error) {
	if err := checkPlaceIDs(args.IDs); err != nil {
		return nil, err
	}
	values := idValues(args.IDs)
	extra := noCache(args.NoCache)

	return func(ctx context.Context, client *Client) (any, error) {
		var answer map[string]any
		info, err := client.get(ctx, "get place descriptions", descriptionsPath, values, extra, &answer)
		if err != nil {
			return nil, err
		}
		return shapedResult(descriptionsAnswerShape, answer, info), nil
	}, nil
}
