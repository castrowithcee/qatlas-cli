// poisArguments are the arguments of brave.pois.get.
type poisArguments struct {
	IDs        []string `json:"ids"`
	SearchLang string   `json:"search_lang"`
	UILang     string   `json:"ui_lang"`
	Units      string   `json:"units"`
	Latitude   *float64 `json:"latitude"`
	Longitude  *float64 `json:"longitude"`
	NoCache    *bool    `json:"no_cache"`
}

// preparePOIs checks every argument; the request is built only from what passed.
func preparePOIs(args poisArguments) (run, error) {
	position := location{Latitude: args.Latitude, Longitude: args.Longitude}
	for _, check := range []error{
		checkPlaceIDs(args.IDs),
		checkEnum("search_lang", args.SearchLang, searchLanguages),
		checkEnum("ui_lang", args.UILang, uiLanguages),
		checkEnum("units", args.Units, unitSystems),
		position.check(),
	} {
		if check != nil {
			return nil, check
		}
	}
	values := idValues(args.IDs)
	text(values, "search_lang", args.SearchLang)
	text(values, "ui_lang", args.UILang)
	text(values, "units", args.Units)
	header := position.headers()
	for name, value := range noCache(args.NoCache) {
		header[name] = value
	}

	return func(ctx context.Context, client *Client) (any, error) {
		var answer map[string]any
		info, err := client.get(ctx, "get places", poisPath, values, header, &answer)
		if err != nil {
			return nil, err
		}
		return shapedResult(poisAnswerShape, answer, info), nil
	}, nil
}

